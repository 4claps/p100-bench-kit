#!/usr/bin/env python3
"""Build results/TABLES.md from every shared result file under results/.

Only bundles that are comparable (standard model) and not marked invalid are
included. One table per (model, module, variant, metric), one row per run,
sorted best first.

usage: python3 tools/build_tables.py [results_dir]
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from benchkit.export import hardware_line, validate_bundle  # noqa: E402

KEY_METRICS = {  # the headline numbers, shown first; everything else follows
    "speed": ["tg128@0", "tg128@16384", "pp512@0", "pp512@16384"],
    "server": ["code.tg", "prose.tg", "prose.pp"],
    "offload": ["tg128@0", "pp512@0"],
    "agent": ["total.pass_rate", "total.wall"],
}


def load(results_dir: Path) -> tuple[list[dict], list[str]]:
    bundles, skipped = [], []
    for p in sorted(results_dir.rglob("*.json")):
        try:
            b = json.loads(p.read_text())
            validate_bundle(b)
        except (ValueError, OSError) as e:
            skipped.append(f"{p.relative_to(results_dir)}: {e}")
            continue
        if not b["spec"].get("comparable"):
            skipped.append(f"{p.relative_to(results_dir)}: custom model, not comparable")
            continue
        if b["run"].get("invalid"):
            skipped.append(f"{p.relative_to(results_dir)}: marked invalid ({b['run'].get('invalid_reason')})")
            continue
        b["_file"] = str(p.relative_to(results_dir))
        bundles.append(b)
    return bundles, skipped


def build(results_dir: Path) -> str:
    bundles, skipped = load(results_dir)
    tables: dict = defaultdict(list)
    for b in bundles:
        for mod, variants in b["summary"].items():
            for var, mets in variants.items():
                for met, s in mets.items():
                    tables[(b["spec"]["model"], mod, var, met)].append((b, s))
    out = ["# Shared results", "",
           f"{len(bundles)} runs. Generated by `tools/build_tables.py`; do not edit by hand.", ""]
    for model in sorted({k[0] for k in tables}):
        out += [f"## {model}", ""]
        for mod in ("speed", "server", "offload", "agent"):
            keys = [k for k in tables if k[0] == model and k[1] == mod]
            order = KEY_METRICS.get(mod, [])
            keys.sort(key=lambda k: (order.index(k[3]) if k[3] in order else 99, k[2], k[3]))
            for k in keys:
                if k[3] not in order:
                    continue
                rows = tables[k]
                lower_better = k[3].endswith("wall")
                rows.sort(key=lambda r: r[1]["median"], reverse=not lower_better)
                unit = rows[0][1]["unit"]
                out += [f"### {mod} · {k[2]} · {k[3]}" + (f" ({unit})" if unit else ""), "",
                        "| hardware | GPUs | engine | median | min–max | n | file |", "|---|---|---|---|---|---|---|"]
                for b, s in rows:
                    out.append(f"| {hardware_line(b.get('snapshot'))} | {len(b['spec'].get('gpus') or [])} | "
                               f"{b['spec'].get('engine')} | {s['median']} | {s['min']:.4g}–{s['max']:.4g} | "
                               f"{s['n']} | {b['_file']} |")
                out.append("")
    if skipped:
        out += ["## Skipped files", ""] + [f"- {s}" for s in skipped] + [""]
    return "\n".join(out)


if __name__ == "__main__":
    d = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "results"
    (d / "TABLES.md").write_text(build(d))
    print(f"wrote {d / 'TABLES.md'}")
